/**
 * Размер шрифта для встроенных стилей: в обычной теме ровно столько пикселей, сколько указано,
 * а в режиме «Для мамы» мелкий и обычный текст увеличивается (--fs-scale) и не опускается ниже --fs-min,
 * крупные числа и заголовки (от 24px) почти не растут (--fs-scale-lg).
 */
export const fs = (px: number): string =>
  `max(calc(${String(px)}px * var(${px >= 24 ? '--fs-scale-lg' : '--fs-scale'})), var(--fs-min))`;
